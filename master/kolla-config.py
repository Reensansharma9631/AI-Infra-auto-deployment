#!/usr/bin/env python3
"""Generate /etc/kolla/globals.yml and /etc/kolla/multinode from a small JSON spec (the UI writes this spec).
usage: kolla-config.py spec.json [--etc /etc/kolla] [--share <venv>/share/kolla-ansible]
spec: {"control":[ip..], "compute":[ip..], "storage":[ip..], "user":"root", "ssh_key":"/opt/airgap/ssh/id_ed25519",
       "vip":"10.0.0.50", "network_interface":"eth0", "external_interface":"eth1", "registry":"10.0.0.5:5000",
       "virt_type":"kvm", "cinder_lvm":false, "lvm_vg":"cinder-volumes"}"""
import argparse, ipaddress, json, pathlib, re, sys

ap = argparse.ArgumentParser(); ap.add_argument("spec"); ap.add_argument("--etc", default="/etc/kolla")
ap.add_argument("--share", required=True); a = ap.parse_args()
s = json.load(open(a.spec)); etc = pathlib.Path(a.etc); etc.mkdir(parents=True, exist_ok=True)
for k in ("control", "compute", "vip", "network_interface", "external_interface", "registry"):
    if not s.get(k): sys.exit(f"spec: '{k}' is required")
if len(s["control"]) not in (1, 3):
    sys.exit("spec: use 1 controller (lab) or 3 controllers (HA: MariaDB Galera + RabbitMQ need an odd quorum)")
for ip in s["control"] + s["compute"] + s.get("storage", []) + [s["vip"]]:
    ipaddress.ip_address(ip)
if s["vip"] in s["control"]:
    sys.exit("spec: the VIP must be a free address, not a controller IP")

def hosts(ips): return "\n".join(f"{ip} ansible_user={s.get('user', 'root')} ansible_ssh_private_key_file={s.get('ssh_key', '')}".rstrip()
                                 + (" ansible_become=true" if s.get("user", "root") != "root" else "") for ip in ips)
inv = (pathlib.Path(a.share) / "ansible/inventory/multinode").read_text()
head_end = inv.index("[baremetal:children]")
storage = s.get("storage") or []
new_head = f"""[control]
{hosts(s['control'])}

[network]
{hosts(s['control'])}

[compute]
{hosts(s['compute'])}

[monitoring]
{hosts(s['control'][:1])}

[storage]
{hosts(storage)}

[deployment]
localhost       ansible_connection=local

"""
(etc / "multinode").write_text(new_head + inv[head_end:])

g = f"""---
# generated by airgap installer (master/kolla-config.py) - safe to re-generate
kolla_base_distro: "ubuntu"
openstack_release: "2026.1"
node_custom_config: "{etc}/config"

# --- air-gap: images from the master's registry, docker from Ubuntu's archive (no download.docker.com)
docker_registry: "{s['registry']}"
docker_namespace: "openstack.kolla"
docker_registry_insecure: true
enable_docker_repo: false
docker_apt_package: "docker.io"

# --- networking
network_interface: "{s['network_interface']}"
neutron_external_interface: "{s['external_interface']}"
kolla_internal_vip_address: "{s['vip']}"
enable_haproxy: "yes"
enable_keepalived: "yes"
neutron_plugin_agent: "ovn"
enable_neutron_provider_networks: "yes"

# --- services
enable_keystone: "yes"
enable_glance: "yes"
enable_placement: "yes"
enable_nova: "yes"
enable_neutron: "yes"
enable_horizon: "yes"
enable_heat: "yes"
enable_cinder: "{'yes' if storage else 'no'}"
enable_cinder_backend_lvm: "{'yes' if s.get('cinder_lvm') and storage else 'no'}"
cinder_volume_group: "{s.get('lvm_vg', 'cinder-volumes')}"
enable_openstack_core: "yes"
nova_compute_virt_type: "{s.get('virt_type', 'kvm')}"
"""
(etc / "globals.yml").write_text(g)
print(f"wrote {etc}/multinode and {etc}/globals.yml  (control={len(s['control'])} compute={len(s['compute'])} storage={len(storage)})")
